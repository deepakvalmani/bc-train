"""Generate src/params.h and src/tune_gen.h from src/params.base.h so every scalar constant becomes a per-map tunable.
python tools/gen_tune.py bots/v46          (reads src/params.base.h, src/tune_exclude.txt; writes src/params.h, src/tune_gen.h)
Names in tune_exclude.txt (and anything draft.cpp uses) stay compile-time constants.
tune_gen.h holds struct Tune{...} with defaults = params.base.h values and macros NAME -> tune::g.NAME."""
import re, sys, pathlib
d = pathlib.Path(sys.argv[1]) / "src"
base = (d / "params.base.h").read_text(encoding="utf8")
excl = set()
ef = d / "tune_exclude.txt"
if ef.exists(): excl = {l.strip() for l in ef.read_text().split() if l.strip()}
draft = (d / "draft.cpp").read_text(encoding="utf8")
excl |= set(re.findall(r"\b[A-Z][A-Z0-9_]{2,}\b", draft))
pat = re.compile(r"^constexpr\s+(bool|int|float|double)\s+([A-Z][A-Z0-9_]*)\s*=\s*([^;\[\]]+?);(.*)$")
out_lines, fields = [], []
for line in base.splitlines():
    m = pat.match(line.strip())
    if m and m.group(2) not in excl and "[]" not in line:
        t, n, v, rest = m.groups(); fields.append((t, n, v.strip()))
        out_lines.append(f"// tunable (see tune_gen.h): {n} = {v.strip()}{rest}")
    else:
        out_lines.append(line)
(d / "params.h").write_text("\n".join(out_lines) + '\n#include "tune_gen.h"\n', encoding="utf8")
g = ["#pragma once", "// GENERATED by tools/gen_tune.py from params.base.h. Do not edit; edit params.base.h or map_tuning.h.",
     "#include \"map_strategy.h\"", "namespace tune {", "struct Tune {"]
for t, n, v in fields:
    v2 = v + ("f" if t == "float" and not v.endswith("f") and re.match(r"^-?[0-9.eE]+$", v) else "")
    g.append(f"    {t} {n} = {v2};")
pm = {}
pf = d / "tune_policy_map.txt"
if pf.exists():
    for l in pf.read_text().splitlines():
        if l.strip(): n, f = l.split(); pm[n] = f
names = {n for _, n, _ in fields}
g += ["};", "inline Tune g;", "inline bool inited = false;",
      "inline void apply_policy(Tune& t, const map_policies::Policy& p) {"]
for n, f in pm.items():
    if n in names: g.append(f"    t.{n} = p.{f};")
g += ["}", '#include "map_tuning.h"',
      "inline void init() {", "    if (inited) return; inited = true;",
      "    g = Tune{};", "    apply_policy(g, map_strategy::policy());",
      "    apply_map(map_strategy::current_map(), g);",
      "    auto cl = [](int& v, int lo, int hi) { if (v < lo) v = lo; if (v > hi) v = hi; };",
      "    for (int* f : {&g.TANK_ITEM_FAMILY1, &g.TANK_ITEM_FAMILY2, &g.TANK_ITEM_FAMILY3, &g.CASTER_ITEM_FAMILY1, &g.CASTER_ITEM_FAMILY2, &g.CASTER_ITEM_FAMILY3, &g.MELEE_ITEM_FAMILY1, &g.MELEE_ITEM_FAMILY2, &g.MELEE_ITEM_FAMILY3}) cl(*f, 0, 6);",
      "    for (int* f : {&g.TANK_ITEM_STAT1, &g.TANK_ITEM_STAT2, &g.TANK_ITEM_STAT3, &g.CASTER_ITEM_STAT1, &g.CASTER_ITEM_STAT2, &g.CASTER_ITEM_STAT3, &g.MELEE_ITEM_STAT1, &g.MELEE_ITEM_STAT2, &g.MELEE_ITEM_STAT3, &g.TANK_POWER_STAT, &g.CASTER_POWER_STAT, &g.MELEE_POWER_STAT}) cl(*f, 0, 2);",
      "    cl(g.CUSTOM_EMBLEM_COUNT, 0, 3); cl(g.BANK_MIN, 1, 100000); if (g.BANK_MAX < g.BANK_MIN) g.BANK_MAX = g.BANK_MIN;",
      "    cl(g.ENGAGE_TTL, 0, 249); cl(g.FUEL_RESERVE, 1, 100000); cl(g.NAV_BUILD_FUEL, 1, 100000); cl(g.PATH_BUILD_FUEL, 1, 100000);",
      "    if (g.SPAWN_HEAL_HP < 0.f) g.SPAWN_HEAL_HP = 0.f; if (g.SPAWN_HEAL_HP > 1.f) g.SPAWN_HEAL_HP = 1.f;",
      "}", "} // namespace tune"]
for t, n, v in fields: g.append(f"#define {n} (tune::g.{n})")
(d / "tune_gen.h").write_text("\n".join(g) + "\n", encoding="utf8")
(d / "tune_fields.txt").write_text("\n".join(f"{t} {n} {v}" for t, n, v in fields) + "\n", encoding="utf8")
print("tunable fields:", len(fields), "excluded names:", len(excl))
